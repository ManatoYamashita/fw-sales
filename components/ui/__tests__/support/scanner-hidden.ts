/**
 * Tailwind の自動ソース検出に拾わせずにクラス名を組み立てる (#265)。
 *
 * ## なぜ要るのか
 *
 * 走査対象は散文だけではなく**ソースコードそのもの**で、テストへ渡した引数や説明
 * コメントに書いた文字列も候補になる。使っていないクラスでも本番 CSS に規則が生まれ、
 * 任意値なら `height: 1notaunit` のような**不正な宣言がそのまま焼き込まれる**
 * (`docs/architecture/responsive.md` §4.2)。
 *
 * 旧クラスを禁じるガードは、needle をソースへ逐語で書くと**ガード自身がその旧クラスを
 * CSS へ延命させる**。実測では md 版の 4 列化が 120 バイト、88px の任意値高さが
 * 41 バイト残っていた。
 *
 * ## 使い方
 *
 * 走査は静的な文字列しか読まないので、実行時に連結すれば候補にならない。
 * **分割位置は「どの断片も単独ではクラスとして解決しないこと」で選ぶ。**
 * 実在するクラスを断片にすると、その断片が候補として拾われて元の木阿弥になる。
 * `md:grid-` と `cols-4` はどちらも解決先を持たないので 0 バイトで済む。
 *
 * ## 現在の位置づけ
 *
 * **一次防御はここではない。** `app/globals.css` が `source(none)` で自動ソース検出を
 * 止め、テストとドキュメントを走査対象から外している (`__tests__/tailwind-source-scope.test.ts`
 * がその設定を固定する)。needle を逐語で書いても、いまは本番 CSS へ届かない。
 *
 * それでも残すのは、除外設定が外れたときに効く二次防御だからで、`hidden()` を
 * 増やして事故を防ぐ運用には**戻さない**。それは英文散文に現れるごく普通の単語
 * (`collapse` や `lowercase` など) には勝てないことが実測で分かっている。
 */
export function hidden(...parts: string[]): string {
  return parts.join("");
}
